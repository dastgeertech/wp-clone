import {
  AngularNodeAppEngine,
  createNodeRequestHandler,
  isMainModule,
  writeResponseToNodeResponse,
} from '@angular/ssr/node';
import compression from 'compression';
import express from 'express';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const serverDistFolder = dirname(fileURLToPath(import.meta.url));
const browserDistFolder = resolve(serverDistFolder, '../browser');

/** API base used for server-to-server calls (never exposed to the browser). */
const API_URL = (process.env['API_URL'] ?? 'http://localhost:3333/api').replace(/\/$/, '');
const API_ORIGIN = API_URL.replace(/\/api$/, '');

const app = express();
const angularApp = new AngularNodeAppEngine();

app.disable('x-powered-by');
app.use(compression());

/* --------------------------------------------------------------
   Uploaded media → proxied to the API so URLs stay same-origin
   (critical for caching + og:image).
--------------------------------------------------------------- */
app.use('/uploads', async (req, res, next) => {
  try {
    const r = await fetch(`${API_ORIGIN}/uploads${req.url}`);
    if (!r.ok) return next();
    res.status(r.status);
    res.setHeader('content-type', r.headers.get('content-type') ?? 'application/octet-stream');
    res.setHeader('cache-control', 'public, max-age=31536000, immutable');
    res.setHeader('access-control-allow-origin', '*');
    res.send(Buffer.from(await r.arrayBuffer()));
  } catch {
    next();
  }
});

/* --------------------------------------------------------------
   robots.txt + XML sitemap generated by the API
--------------------------------------------------------------- */
for (const [path, type] of [
  ['/robots.txt', 'text/plain; charset=utf-8'],
  ['/sitemap.xml', 'application/xml; charset=utf-8'],
] as const) {
  app.get(path, async (_req, res) => {
    try {
      const endpoint = path === '/robots.txt' ? '/seo/robots' : '/seo/sitemap';
      const r = await fetch(`${API_URL}${endpoint}`);
      if (!r.ok) throw new Error(String(r.status));
      res.status(200).setHeader('content-type', type);
      res.setHeader('cache-control', 'public, max-age=300');
      res.send(await r.text());
    } catch {
      res.status(502).send('Upstream unavailable');
    }
  });
}

/* --------------------------------------------------------------
   Real HTTP 301s for renamed slugs (Redirect table) + trailing-slash
   canonicalization for `/%postname%/` permalinks
--------------------------------------------------------------- */
const redirectCache = new Map<string, { to: string; status: number } | null>();
const REDIRECT_TTL = 60_000;
const redirectStampedAt = new Map<string, number>();
const existsCache = new Map<string, boolean>();
const existsStampedAt = new Map<string, number>();
const SKIP_REDIRECT = /^\/(uploads|assets|themes)\//;
const ARCHIVE_PREFIXES = new Set(['category', 'tag', 'author']);

const fetchJson = async <T>(url: string): Promise<T | null> => {
  try {
    const r = await fetch(url, { signal: AbortSignal.timeout(4000) });
    return r.ok ? ((await r.json()) as T) : null;
  } catch {
    return null;
  }
};

const headOk = (url: string): Promise<boolean> =>
  fetch(url, { method: 'HEAD', signal: AbortSignal.timeout(4000) })
    .then((r) => r.ok)
    .catch(() => false);

/** Does content resolve for this path (always passed WITH trailing slash)? */
async function contentExists(pathWithSlash: string): Promise<boolean> {
  const path = pathWithSlash.replace(/\/+$/, '');
  const segs = path.slice(1).split('/').filter(Boolean);
  const stamp = existsStampedAt.get(path) ?? 0;
  if (Date.now() - stamp < REDIRECT_TTL) return existsCache.get(path) ?? false;

  let exists = false;
  if (segs.length === 1 && segs[0] !== 'search') {
    // could be a post or a page
    const slug = encodeURIComponent(segs[0]);
    const [post, page] = await Promise.all([
      headOk(`${API_URL}/content/posts/${slug}`),
      headOk(`${API_URL}/content/pages/${slug}`),
    ]);
    exists = post || page;
  } else if (segs.length === 2 && ARCHIVE_PREFIXES.has(segs[0])) {
    const slug = encodeURIComponent(segs[1]);
    exists =
      segs[0] === 'author'
        ? await headOk(`${API_URL}/content/authors/${slug}`)
        : await headOk(`${API_URL}/content/terms/${segs[0].toUpperCase()}/${slug}`);
  }
  // Any other path shape: never redirect — let the router 404 it.

  existsCache.set(path, exists);
  existsStampedAt.set(path, Date.now());
  return exists;
}

app.use(async (req, res, next) => {
  if (req.method !== 'GET' || req.headers.accept?.includes('application/json')) return next();
  const from = req.path;
  if (from === '/' || SKIP_REDIRECT.test(from) || /\.[a-z0-9]+$/i.test(from)) return next();

  const now = Date.now();

  /* 1. renamed slug — try both slash forms so `/old` and `/old/` both 301 */
  const renameKeys = from.endsWith('/') ? [from, from.slice(0, -1)] : [from, `${from}/`];
  for (const key of renameKeys) {
    let target = redirectCache.get(key) ?? null;
    if (!target || now - (redirectStampedAt.get(key) ?? 0) > REDIRECT_TTL) {
      target = await fetchJson<{ to: string; status: number }>(
        `${API_URL}/content/redirect?from=${encodeURIComponent(key)}`,
      );
      redirectCache.set(key, target);
      redirectStampedAt.set(key, now);
    }
    if (target?.to) {
      redirectCache.delete(key); // a redirect only applies once
      redirectStampedAt.delete(key);
      // redirect rows store bare paths — land on the canonical trailing slash
      const to = target.to.endsWith('/') ? target.to : `${target.to}/`;
      return res.redirect(target.status || 301, to);
    }
  }

  /* 2. trailing-slash canonicalization for real content/archive URLs */
  if (!from.endsWith('/') && (await contentExists(`${from}/`))) {
    return res.redirect(301, `${from}/`);
  }

  next();
});

/* --------------------------------------------------------------
   Serve hashed static assets from /browser
--------------------------------------------------------------- */
app.use(
  express.static(browserDistFolder, {
    maxAge: '1y',
    index: false,
    redirect: false,
    setHeaders: (res, filePath) => {
      // index.html must always revalidate so deploys are picked up
      if (filePath.endsWith('index.html')) res.setHeader('cache-control', 'no-cache');
    },
  }),
);

/* --------------------------------------------------------------
   SSR: render every other request, with CDN-friendly caching
--------------------------------------------------------------- */
app.use('/**', (req, res, next) => {
  angularApp
    .handle(req)
    .then((response) => {
      if (!response) return next();
      if (
        req.method === 'GET' &&
        !res.getHeader('cache-control') &&
        !req.path.startsWith('/api')
      ) {
        // HTML pages: 1 min in the browser, 2 min at the edge, revalidate after
        res.setHeader(
          'cache-control',
          'public, max-age=60, s-maxage=120, stale-while-revalidate=600',
        );
        res.setHeader('vary', 'Accept-Encoding');
      }
      return writeResponseToNodeResponse(response, res);
    })
    .catch(next);
});

/**
 * Start the server if this module is the main entry point, or it is ran via PM2.
 * The server listens on the port defined by the `PORT` environment variable, or defaults to 4000.
 */
if (isMainModule(import.meta.url) || process.env['pm_id']) {
  const port = process.env['PORT'] || 4000;
  const server = app.listen(port, async (error?: Error) => {
    if (error) {
      throw error;
    }

    console.log(`Node Express server listening on http://localhost:${port}`);
    // Set when Nx waits for this server to be ready
    if (process.env['NX_READY_SIGNAL_SOCKET']) {
      try {
        // Function keeps TypeScript and bundlers from rewriting or bundling the import
        const load = new Function('s', 'return import(s)') as (s: string) => Promise<{ emitReadySignal(server: unknown): boolean }>;
        (await load('@nx/js/ready-signal')).emitReadySignal(server);
      } catch {
        // @nx/js isn't installed
      }
    }
  });
}

/**
 * Request handler used by the Angular CLI (for dev-server and during build) or Firebase Cloud Functions.
 */
export const reqHandler = createNodeRequestHandler(app);
